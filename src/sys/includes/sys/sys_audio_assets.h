/*
【模块职责】集中持有并注册所有FATFS音频PCM，并把基础资源与双蛇杖延迟资源分开调度。
【重要约束】PCM加载后常驻到重启，确保应用打开和异步播放期间地址稳定；本模块不决定播放总线、音量或播放时机。
*/
#pragma once

namespace SysAudioAssets
{
    /**
     * 【接口说明】同步预加载并注册启动所需的基础FATFS音频，不包含双蛇杖资源。
     * 【返回值】全部成功返回true；单个资源失败不阻止其余资源继续加载。
     * 【重复调用】已经成功加载的资源会直接复用，不重复申请PSRAM。
     */
    bool PreloadCore();

    /**
     * 【接口说明】每次最多加载并注册一份双蛇杖音频，供SysRes_Update在主循环分帧调用。
     * 【输出】complete在18份资源均已尝试后置true；函数返回本次资源是否成功。
     * 【重要约束】即使单份失败也会推进游标，避免缺失文件导致每帧无限重试。
     */
    bool PreloadCaduceusStep(bool &complete);
}
